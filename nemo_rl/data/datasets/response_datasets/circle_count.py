import json
from typing import Any

from datasets import Dataset

from nemo_rl.data.datasets.raw_dataset import RawDataset

# Mirrors the circle_count NeMo-Gym environment
# (3rdparty/Gym-workspace/Gym/resources_servers/circle_count): count the circles
# of a target color in the image and answer with \boxed{N}. The gym verifier
# regex is mirrored by `boxed_numeric_reward` in nemo_rl/environments/rewards.py.
CIRCLE_COUNT_SYSTEM_PROMPT = (
    "You are a visual assistant. Count the number of circles of the specified color in the image. "
    "Output your final answer in \\boxed{} format, e.g. \\boxed{3}."
)


def format_circle_count_dataset(datum_dict: dict[str, Any]) -> dict[str, Any]:
    """Format a circle-count JSONL row (gym produce format) for VLM training."""
    row = json.loads(datum_dict["raw"])
    params = row["responses_create_params"]

    image_url = None
    question_text = ""
    for message in params["input"]:
        if message["role"] != "user":
            continue
        for content in message["content"]:
            if content["type"] == "input_image":
                image_url = content["image_url"]
            elif content["type"] == "input_text":
                question_text = content["text"]

    expected_count = sum(
        1 for c in row["circles"] if c["color"] == row["target_color"]
    )

    return {
        "messages": [
            {
                "role": "user",
                "content": [
                    {"type": "image", "image": image_url},
                    {"type": "text", "text": question_text},
                ],
            },
            {"role": "assistant", "content": str(expected_count)},
        ],
        "task_name": datum_dict["task_name"],
    }


class CircleCountSFTDataset(RawDataset):
    """SFT rows for the circle-count task: messages already in final form.

    Emitted by /brev/circle-count-gym/gen_sft.py (image data URL + gym system
    prompt + templated assistant answer ending in \\boxed{N}).

    Args:
        data_path: Path to the SFT JSONL.
    """

    def __init__(self, data_path: str, **kwargs):
        self.task_name = "circle-count-sft"
        rows = []
        with open(data_path) as f:
            for line in f:
                rows.append(json.loads(line))
        self.dataset = Dataset.from_dict(
            {
                "messages": [r["messages"] for r in rows],
                "task_name": [self.task_name] * len(rows),
            }
        )


class CircleCountDataset(RawDataset):
    """Circle-count dataset generated by Gym resources_servers/circle_count/generate_data.py.

    Args:
        data_path: Path to the JSONL produced by generate_data.py.
    """

    def __init__(self, data_path: str, **kwargs):
        self.task_name = "circle-count"
        with open(data_path) as f:
            raw_lines = [line for line in f]
        self.dataset = Dataset.from_dict(
            {
                "raw": raw_lines,
                "task_name": [self.task_name] * len(raw_lines),
            }
        )
